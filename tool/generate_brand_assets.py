#!/usr/bin/env python3
"""Generate every KashU logo asset from one definition of the mark.

    python3 tool/generate_brand_assets.py

The mark is "Cashew U": a cream cashew catching a gold coin on a lavender
tile, the ink colour of the ₹100 note (chosen 22 Oct 2026, WBS 1.11.3). Its
shapes and colours are defined once, below, in a 100 x 100 design space, and
everything that shows the logo is written from them, so nothing can drift:

  assets/images/app_icon.png                    1024 px master, full bleed
  ios/Runner/Assets.xcassets/AppIcon.appiconset every size in its Contents.json
  android/app/src/main/res/
    mipmap-*/ic_launcher.png, ic_launcher_round.png   legacy icons (API 24-25)
    drawable/ic_launcher_foreground.xml               adaptive icon (vector)
    drawable/ic_launcher_monochrome.xml               themed icon, Android 13+
    values/ic_launcher_background.xml                 the tile colour
    mipmap-anydpi-v26/ic_launcher.xml, ic_launcher_round.xml
  web/favicon.png, web/icons/Icon-*.png, Icon-maskable-*.png
  store/play/icon-512.png, store/play/feature-graphic-1024x500.png
  lib/core/constants/brand_mark.dart            the same geometry for Flutter

Requires Pillow. The feature graphic is set in the app's own bundled fonts
(assets/fonts/), so no system font is involved.
"""
import json
import os
import re

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ── The mark, in a 100 x 100 design space ───────────────────────────────────
TILE_RADIUS = 23                   # corner radius of the rounded tile
NUT_PATH = ("M30 38C26 58 40 72 56 70C70 68 76 56 72 42C70 35 61 34 61 42"
            "C61 52 55 58 49 57C42 56 40 48 40 40C40 33 31 31 30 38Z")
NUT_OFFSET = (-1, 6)               # where the cashew sits on the tile
COIN_CENTER, COIN_R = (50.5, 43), 10
# One-colour version (Android themed icon): smaller and recentred, with a
# slimmer coin so it stays apart from the cashew in a single tint.
MONO_SCALE, MONO_ANCHOR, MONO_COIN_R = 0.72, (50, 53), 9
# The wordmark's "U" is the cashew and coin cropped to this box (left, top,
# width, height), drawn this many times the font size tall.
GLYPH_BOX, GLYPH_EM = (26, 32, 48, 44), 0.835

# ── Palette: "Sau Lavender", from the ₹100 note ─────────────────────────────
TILE = "#7E6BB5"    # the icon tile
NUT = "#F5F1FC"     # cashew cream
COIN = "#FFD23F"    # coin gold
INK = "#382B63"     # deep ink: the wordmark on light grounds
PAPER = "#DCD3EE"   # note paper: light grounds, the U on dark ones

SS = 4              # supersampling factor for the rasters
RES = "android/app/src/main/res"
LEGACY_PX = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
GENERATED = "Generated by tool/generate_brand_assets.py; edit the mark there."


# ── Geometry ────────────────────────────────────────────────────────────────

def nut_segments():
    """NUT_PATH as a start point and cubic segments, NUT_OFFSET applied.

    Only absolute M, C and Z are supported, which is all the mark uses.
    """
    dx, dy = NUT_OFFSET
    start, cubics, cmd, nums = None, [], None, []
    for tok in re.findall(r"[A-Za-z]|-?\d+(?:\.\d+)?", NUT_PATH):
        if tok.isalpha():
            if tok not in "MCZ":
                raise SystemExit(f"NUT_PATH: unsupported command {tok}")
            cmd, nums = tok, []
            continue
        nums.append(float(tok))
        if cmd == "M" and len(nums) == 2:
            start, nums = (nums[0] + dx, nums[1] + dy), []
        elif cmd == "C" and len(nums) == 6:
            cubics.append(tuple((nums[k] + dx, nums[k + 1] + dy)
                                for k in (0, 2, 4)))
            nums = []
    return start, cubics


def nut_polygon(steps=48):
    """The cashew outline flattened to points, for rasterising."""
    start, cubics = nut_segments()
    pts, p0 = [start], start
    for p1, p2, p3 in cubics:
        for i in range(1, steps + 1):
            t = i / steps
            u = 1 - t
            pts.append(tuple(u ** 3 * a + 3 * u * u * t * b + 3 * u * t * t * c
                             + t ** 3 * d for a, b, c, d in zip(p0, p1, p2, p3)))
        p0 = p3
    return pts


def mark_bounds():
    """Bounding box (left, top, width, height) of the cashew and coin."""
    xs, ys = zip(*nut_polygon())
    (cx, cy), r = COIN_CENTER, COIN_R
    left, top = min(min(xs), cx - r), min(min(ys), cy - r)
    return (left, top, max(max(xs), cx + r) - left,
            max(max(ys), cy + r) - top)


# ── Rasters ─────────────────────────────────────────────────────────────────

def rgb(hex_colour):
    return tuple(int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))


def draw(width, height, box=(0, 0, 100, 100), tile="rounded", nut=NUT,
         coin=COIN):
    """Render the design-space `box` into a width x height RGBA image.

    tile: "rounded" (the app icon), "square" (full bleed, for platforms that
    cut their own shape) or None (the cashew and coin alone).
    """
    w, h = width * SS, height * SS
    x0, y0, bw, bh = box
    sx, sy = w / bw, h / bh

    def at(x, y):
        return (x - x0) * sx, (y - y0) * sy

    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if tile == "square":
        d.rectangle((0, 0, w, h), fill=rgb(TILE))
    elif tile == "rounded":
        d.rounded_rectangle((0, 0, w - 1, h - 1), radius=TILE_RADIUS * sx,
                            fill=rgb(TILE))
    d.polygon([at(*p) for p in nut_polygon()], fill=rgb(nut))
    cx, cy = at(*COIN_CENTER)
    r = COIN_R * sx
    d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=rgb(coin))
    # Resample premultiplied so transparent edges don't darken.
    return img.convert("RGBa").resize((width, height), Image.LANCZOS) \
        .convert("RGBA")


def icon(px, tile="rounded"):
    return draw(px, px, tile=tile)


def circle(img):
    """Cut an icon to a circle (legacy round launcher icons)."""
    big = Image.new("L", (img.width * SS, img.height * SS), 0)
    ImageDraw.Draw(big).ellipse((0, 0, big.width - 1, big.height - 1), fill=255)
    mask = big.resize(img.size, Image.LANCZOS)
    out = img.copy()
    out.putalpha(Image.composite(img.getchannel("A"), mask, mask))
    return out


def save(img, rel, rgb_only=False):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    (img.convert("RGB") if rgb_only else img).save(path, optimize=True)
    print("wrote", rel)


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", rel)


# ── Platforms ───────────────────────────────────────────────────────────────

def master():
    save(icon(1024, tile="square"), "assets/images/app_icon.png", True)


def ios():
    folder = "ios/Runner/Assets.xcassets/AppIcon.appiconset"
    with open(os.path.join(ROOT, folder, "Contents.json")) as f:
        images = json.load(f)["images"]
    for entry in images:
        if "filename" not in entry:
            continue
        points = float(entry["size"].split("x")[0])
        scale = int(entry["scale"].rstrip("x"))
        # iOS cuts its own corners and rejects alpha: full bleed, RGB.
        save(icon(round(points * scale), tile="square"),
             f"{folder}/{entry['filename']}", True)


def _n(v):
    return f"{v:g}"


def _coin_path(r):
    cx, cy = COIN_CENTER
    return (f"M{_n(cx - r)},{_n(cy)}a{_n(r)},{_n(r)} 0 1,0 {_n(2 * r)},0"
            f"a{_n(r)},{_n(r)} 0 1,0 {_n(-2 * r)},0Z")


def _vector(mono):
    """An adaptive-icon layer: the 100-unit design space mapped onto the
    72dp of the 108dp layer that a launcher mask leaves visible."""
    nut, coin = ("#FFFFFFFF", "#FFFFFFFF") if mono else (NUT, COIN)
    inner = (f'        <group android:translateX="{_n(NUT_OFFSET[0])}" '
             f'android:translateY="{_n(NUT_OFFSET[1])}">\n'
             f'            <path android:fillColor="{nut}"\n'
             f'                android:pathData="{NUT_PATH}"/>\n'
             f'        </group>\n'
             f'        <path android:fillColor="{coin}"\n'
             f'            android:pathData="{_coin_path(MONO_COIN_R if mono else COIN_R)}"/>\n')
    if mono:
        tx = 50 - MONO_SCALE * MONO_ANCHOR[0]
        ty = 50 - MONO_SCALE * MONO_ANCHOR[1]
        inner = (f'        <group android:scaleX="{_n(MONO_SCALE)}" '
                 f'android:scaleY="{_n(MONO_SCALE)}"\n'
                 f'            android:translateX="{_n(round(tx, 4))}" '
                 f'android:translateY="{_n(round(ty, 4))}">\n'
                 + "\n".join("    " + line if line else line
                             for line in inner.split("\n"))
                 + "        </group>\n")
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f'<!-- {GENERATED} -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        '    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n'
        '    <group android:scaleX="0.72" android:scaleY="0.72"\n'
        '        android:translateX="18" android:translateY="18">\n'
        f'{inner}'
        '    </group>\n'
        '</vector>\n')


ADAPTIVE = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    f'<!-- {GENERATED}\n'
    '     Adaptive icon (API 26+): lavender tile, the cashew and coin as a\n'
    '     vector inside the 66dp safe zone, and a one-colour layer for\n'
    '     Android 13+ themed icons. -->\n'
    '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
    '    <background android:drawable="@color/ic_launcher_background"/>\n'
    '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
    '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
    '</adaptive-icon>\n')


def android():
    for density, px in LEGACY_PX.items():
        legacy = icon(px)
        save(legacy, f"{RES}/mipmap-{density}/ic_launcher.png")
        save(circle(icon(px, tile="square")),
             f"{RES}/mipmap-{density}/ic_launcher_round.png")
        for old in ("ic_launcher_foreground.png", "ic_launcher_background.png"):
            path = os.path.join(ROOT, RES, f"mipmap-{density}", old)
            if os.path.exists(path):
                os.remove(path)
                print("removed", f"{RES}/mipmap-{density}/{old}")
    write(f"{RES}/values/ic_launcher_background.xml",
          '<?xml version="1.0" encoding="utf-8"?>\n'
          f'<!-- {GENERATED} -->\n'
          '<resources>\n'
          f'    <color name="ic_launcher_background">{TILE}</color>\n'
          '</resources>\n')
    write(f"{RES}/drawable/ic_launcher_foreground.xml", _vector(mono=False))
    write(f"{RES}/drawable/ic_launcher_monochrome.xml", _vector(mono=True))
    for name in ("ic_launcher", "ic_launcher_round"):
        write(f"{RES}/mipmap-anydpi-v26/{name}.xml", ADAPTIVE)


def web():
    save(icon(32), "web/favicon.png")
    for px in (192, 512):
        save(icon(px), f"web/icons/Icon-{px}.png")
        # Maskable: full bleed; the mark sits well inside the 80% safe circle.
        save(icon(px, tile="square"), f"web/icons/Icon-maskable-{px}.png", True)


def _font(rel, px):
    return ImageFont.truetype(os.path.join(ROOT, "assets", "fonts", rel), px)


def feature_graphic():
    """Play's 1024 x 500 banner: the mark and the wordmark on lavender."""
    W, H = 1024, 500
    canvas = Image.new("RGBA", (W, H), rgb(TILE) + (255,))

    bx, by, bw, bh = mark_bounds()
    pad = 2
    box = (bx - pad, by - pad, bw + 2 * pad, bh + 2 * pad)
    mark_h = 250
    mark = draw(round(mark_h * box[2] / box[3]), mark_h, box, tile=None)

    title = _font("quicksand/Quicksand-Bold.ttf", 118)
    sub = _font("plus_jakarta_sans/PlusJakartaSans-SemiBold.ttf", 32)
    glyph_h = round(118 * GLYPH_EM)
    glyph = draw(round(glyph_h * GLYPH_BOX[2] / GLYPH_BOX[3]), glyph_h,
                 GLYPH_BOX, tile=None, nut=PAPER)
    tagline = "Track every investment. Privately."
    kash_w = title.getlength("Kash")
    gap = round(118 * 0.06)
    words_w = kash_w + gap + glyph.width
    text_w = max(words_w, sub.getlength(tagline))

    spacing = 64
    left = round((W - (mark.width + spacing + text_w)) / 2)
    canvas.alpha_composite(mark, (left, (H - mark.height) // 2))

    text_x = left + mark.width + spacing
    baseline = 262
    layer = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    d.text((text_x, baseline), "Kash", font=title, fill=rgb(NUT) + (255,),
           anchor="ls")
    layer.alpha_composite(
        glyph, (round(text_x + kash_w + gap), baseline - glyph.height))
    d.text((text_x + 4, baseline + 64), tagline, font=sub,
           fill=rgb(NUT) + (235,), anchor="ls")
    canvas.alpha_composite(layer)
    return canvas


def store():
    # Play cuts its own corners: full bleed.
    save(icon(512, tile="square"), "store/play/icon-512.png", True)
    save(feature_graphic(), "store/play/feature-graphic-1024x500.png", True)


# ── Flutter ─────────────────────────────────────────────────────────────────

def _dart_colour(hex_colour):
    return f"Color(0xFF{hex_colour[1:].upper()})"


def dart():
    start, cubics = nut_segments()
    ops = [f"    ..moveTo({_n(start[0])}, {_n(start[1])})"]
    for p1, p2, p3 in cubics:
        ops.append("    ..cubicTo(" + ", ".join(
            _n(v) for p in (p1, p2, p3) for v in p) + ")")
    ops[-1] += "\n    ..close();"
    gl, gt, gw, gh = GLYPH_BOX
    write("lib/core/constants/brand_mark.dart", f"""\
// {GENERATED}
// Do not edit by hand: rerun `python3 tool/generate_brand_assets.py`.
import 'dart:ui';

/// The KashU mark, "Cashew U": a cream cashew catching a gold coin on a
/// lavender tile, the ink colour of the ₹100 note. Coordinates are in a
/// 100 × 100 design space, shared with every app icon the same script
/// writes. Drawn in the app by `KashuMark` and `KashuWordmark`
/// (shared/widgets/kashu_logo.dart).
abstract final class BrandMark {{
  /// Sau Lavender, the icon tile.
  static const Color tile = {_dart_colour(TILE)};

  /// Cashew cream.
  static const Color nut = {_dart_colour(NUT)};

  /// Coin gold.
  static const Color coin = {_dart_colour(COIN)};

  /// Deep ink: the wordmark on light grounds.
  static const Color ink = {_dart_colour(INK)};

  /// Note paper: light grounds, and the wordmark's U on dark ones.
  static const Color paper = {_dart_colour(PAPER)};

  static const double tileCornerRadius = {_n(TILE_RADIUS)};
  static const Offset coinCenter = Offset({_n(COIN_CENTER[0])}, {_n(COIN_CENTER[1])});
  static const double coinRadius = {_n(COIN_R)};

  /// The wordmark's U is the cashew and coin cropped to this box, drawn
  /// [glyphHeightPerEm] times the font size tall.
  static const Rect glyphBox = Rect.fromLTWH({_n(gl)}, {_n(gt)}, {_n(gw)}, {_n(gh)});
  static const double glyphHeightPerEm = {_n(GLYPH_EM)};

  /// The cashew, already placed on the tile.
  static Path nutPath() => Path()
{chr(10).join(ops)}
}}
""")


if __name__ == "__main__":
    master()
    ios()
    android()
    web()
    store()
    dart()
